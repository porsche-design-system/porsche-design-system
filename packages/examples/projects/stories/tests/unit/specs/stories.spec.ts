import type { Story } from '@porsche-design-system/story-generator';
import {
  isAccessibilityExample,
  isDefaultExample,
  isStory,
  readStoryExports,
  toAccessibilityModule,
  toStoryModule,
} from '../../../lib/stories';

const story: Story<'p-button'> = { generator: () => [{ tag: 'p-button', children: ['Some label'] }] };
const slotStories = { 'slot-name': { Story: story } };

describe('isDefaultExample()', () => {
  it('tells a default example by its last segment', () => {
    expect(isDefaultExample('components/button/default')).toBe(true);
    expect(isDefaultExample('components/button/form')).toBe(false);
  });
});

describe('isStory()', () => {
  it('is true for a story', () => {
    expect(isStory(story)).toBe(true);
  });

  it.each([undefined, null, {}, slotStories, { generator: 'not a function' }])('is false for %j', (value) => {
    expect(isStory(value)).toBe(false);
  });
});

describe('isAccessibilityExample()', () => {
  it('is true for a pair of an anti-pattern and its recommendation', () => {
    expect(isAccessibilityExample({ name: 'Name', antiPattern: {}, recommended: {} })).toBe(true);
  });

  it.each([undefined, null, story, { antiPattern: {} }])('is false for %j', (value) => {
    expect(isAccessibilityExample(value)).toBe(false);
  });
});

describe('readStoryExports()', () => {
  it('takes the one story of an example', () => {
    expect(readStoryExports('components/button/form', { buttonStoryForm: story })).toEqual({
      story: 'buttonStoryForm',
    });
  });

  it.each([
    ['none', {}],
    ['two stories', { a: story, b: story }],
    ['something else', { buttonSlotStories: slotStories }],
  ])('rejects an example module exporting %s', (_, module) => {
    expect(() => readStoryExports('components/button/form', module)).toThrow(
      '"components/button/form" has to export exactly one story'
    );
  });

  it('tells the stories of a default example apart by their value and by "Controlled" in their name', () => {
    expect(
      readStoryExports('components/popover/default', {
        popoverSlotStories: slotStories,
        popoverStory: story,
        popoverControlledSlotStories: slotStories,
        popoverControlledStory: story,
      })
    ).toEqual({
      story: 'popoverStory',
      slotStories: 'popoverSlotStories',
      controlledStory: 'popoverControlledStory',
      controlledSlotStories: 'popoverControlledSlotStories',
    });
  });

  it('rejects a default example exporting two of the same', () => {
    expect(() => readStoryExports('components/button/default', { buttonStory: story, otherStory: story })).toThrow(
      '"components/button/default" exports two of its story: buttonStory, otherStory'
    );
  });

  it('rejects a default example without its story', () => {
    expect(() => readStoryExports('components/button/default', { buttonSlotStories: slotStories })).toThrow(
      '"components/button/default" exports no story'
    );
  });
});

describe('toStoryModule()', () => {
  it('spreads the data of the example and adds its stories and its description', () => {
    expect(
      toStoryModule('components/popover/default', { story: 'popoverStory', slotStories: 'popoverSlotStories' }, true)
    ).toEqual([
      '// Generated by scripts/build.ts from src/ – do not edit.',
      "import { storyExamples } from '../../../index';",
      "import { popoverSlotStories, popoverStory } from '../../../../src/components/popover/default/story';",
      "import Description from '../../../../src/components/popover/default/example.mdx';",
      '',
      'export default {',
      "  ...storyExamples['components/popover/default'],",
      '  story: popoverStory,',
      '  slotStories: popoverSlotStories,',
      '  Description,',
      '};',
    ]);
  });

  it('imports no description the example does not have', () => {
    expect(toStoryModule('components/button/form', { story: 'buttonStoryForm' }, false).join('\n')).not.toContain(
      'Description'
    );
  });
});

describe('toAccessibilityModule()', () => {
  it('exports the data of the example', () => {
    expect(toAccessibilityModule('components/button/accessibility/icon-only')).toEqual([
      '// Generated by scripts/build.ts from src/ – do not edit.',
      "import { accessibilityExamples } from '../../../../index';",
      '',
      "export default accessibilityExamples['components/button/accessibility/icon-only'];",
    ]);
  });
});
